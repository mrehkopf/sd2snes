#!/usr/bin/env python3
"""Convert the button graphics for the menu's default skin.

    buttons.py <font.png>

<font.png> is the font art (gfx/fontz-16x8-withtees.aseprite, exported with
aseprite -b <file> --save-as font.png): 128x256 pixels, indexed colors, 8
characters of 16x8 pixels per row, color 0 transparent. Characters 0-15 are
the buttons. Writes buttons.chr (FONT payload for characters 0-15, without
the header) and buttons.asm (CGEN chunks with the colors of the three button
palettes) next to this script.
"""
import os
import sys
from PIL import Image

# character -> BG1 palette (see skin-format.md, "Palette"): each palette has
# its own colors, which the buttons in it share
PALETTES = {
    2: [0, 2],                  # SFC A, X: colors 4-15 (36-47)
    3: list(range(4, 16)),      # US A, B, X, Y, L, R, START, SELECT, D-pad: 4-15 (52-63)
    4: [1, 3],                  # SFC B, Y: colors 1-15 (65-79)
}
FIRST_SLOT = {2: 4, 3: 4, 4: 1}
NAMES = ['A (SFC)', 'B (SFC)', 'X (SFC)', 'Y (SFC)', 'A (US)', 'B (US)', 'X (US)', 'Y (US)',
         'L', 'R', 'START', 'SELECT', 'up', 'down', 'left', 'right']


def bgr555(rgb):
    r, g, b = (v >> 3 for v in rgb)
    return r | g << 5 | b << 10


def main(png):
    im = Image.open(png)
    if im.mode != 'P' or im.size != (128, 256):
        sys.exit('%s: expected a 128x256 indexed image' % png)
    pal = im.getpalette()
    px = im.load()
    here = os.path.dirname(os.path.abspath(__file__))

    def cell(c):
        cx, cy = (c % 8) * 16, (c // 8) * 8
        return [[px[cx + x, cy + y] for x in range(16)] for y in range(8)]

    chr_data = bytearray(16 * 64)
    asm = ['; button graphics: colors of the BG1 palettes of characters 0-15',
           '; generated by buttons.py from the font art, do not edit', '']
    for p, chars in PALETTES.items():
        colors = []
        for c in chars:
            for row in cell(c):
                for v in row:
                    if v and bgr555(pal[3 * v:3 * v + 3]) not in colors:
                        colors.append(bgr555(pal[3 * v:3 * v + 3]))
        colors.sort(key=lambda w: ((w & 31) * 3 + (w >> 5 & 31) * 6 + (w >> 10)) * 32768 + w)
        if FIRST_SLOT[p] + len(colors) > 16:
            sys.exit('palette %d: %d colors, room for %d' % (p, len(colors), 16 - FIRST_SLOT[p]))
        slot = {w: FIRST_SLOT[p] + i for i, w in enumerate(colors)}
        for c in chars:
            rows = cell(c)
            for half in range(2):
                for y in range(8):
                    for x in range(8):
                        v = rows[y][8 * half + x]
                        if not v:
                            continue
                        s = slot[bgr555(pal[3 * v:3 * v + 3])]
                        for b in range(4):
                            if s >> b & 1:
                                chr_data[64 * c + 32 * half + 16 * (b >> 1) + 2 * y + (b & 1)] |= 0x80 >> x
        first = 16 * p + FIRST_SLOT[p]
        asm += ['; palette %d: %s' % (p, ', '.join(NAMES[c] for c in chars)),
                'buttons_pal%d .block' % p,
                '  .skin_chunk "CGEN"',
                '  .word %d, %d                  ; first color, number of colors' % (first, len(colors))]
        for i in range(0, len(colors), 8):
            asm.append('  .word ' + ', '.join('$%04x' % w for w in colors[i:i + 8]))
        asm += ['chunk_end:', '.endblock', '']
    open(os.path.join(here, 'buttons.chr'), 'wb').write(chr_data)
    open(os.path.join(here, 'buttons.asm'), 'w').write('\n'.join(asm))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
